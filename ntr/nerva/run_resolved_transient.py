"""Run time-dependent fuel-channel and tie-tube counterflow from NUKE NPZ.

Requires the existing mesh fields, fuel element/channel reconstruction,
and tie-instance reconstruction generated by the standard OpenMC pipeline.
No new neutron transport occurs: the heating shape is held constant.

A real source requires the original statepoint AND matching transport
provenance SHA256. Synthetic input is explicitly opt-in.
"""
from __future__ import annotations
import argparse
import csv
from dataclasses import asdict
import hashlib
import json
import math
from pathlib import Path

import numpy as np

from .resolved_transient import (
    read_resolved_heating, ResolvedParameters, initial_resolved_state,
    advance_resolved
)
from .temporal_convergence import refine_resolved_timestep


def parse_args():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("mesh_fields", type=Path)
    p.add_argument("fuel_reconstruction", type=Path)
    p.add_argument("tie_reconstruction", type=Path)
    p.add_argument("--allow-synthetic", action="store_true")
    p.add_argument("--statepoint", type=Path)
    p.add_argument("--transport-provenance", type=Path)
    p.add_argument("--steps", type=int, default=10)
    p.add_argument("--dt-s", type=float, required=True)
    p.add_argument("--initial-solid-k", type=float, required=True)
    p.add_argument("--initial-gas-k", type=float, required=True)
    p.add_argument("--inlet-temperature-k", type=float, required=True)
    p.add_argument("--expected-power-mw", type=float)
    p.add_argument("--fuel-solid-capacity-j-k", type=float, required=True)
    p.add_argument("--fuel-gas-capacity-j-k", type=float, required=True)
    p.add_argument("--fuel-ua-w-k", type=float, required=True)
    p.add_argument("--tie-solid-capacity-j-k", type=float, required=True)
    p.add_argument("--tie-supply-capacity-j-k", type=float, required=True)
    p.add_argument("--tie-return-capacity-j-k", type=float, required=True)
    p.add_argument("--tie-supply-ua-w-k", type=float, required=True)
    p.add_argument("--tie-return-ua-w-k", type=float, required=True)
    p.add_argument("--h2-cp-reference-j-kg-k", type=float, default=14300.)
    p.add_argument("--gas-enthalpy-model", choices=("nasa7-h2","constant"),
                   default="nasa7-h2")
    p.add_argument("--max-unresolved-fraction", type=float, default=0.5)
    p.add_argument("--refine-levels", type=int, default=0,
                   help="0 disables audit; 3-8 runs 1x,2x,4x... timesteps "
                        "on the same frozen OpenMC heating and checks convergence.")
    p.add_argument("--refine-tolerance-k", type=float, default=0.25,
                   help="Maximum allowed penultimate-to-finest state-field "
                        "temperature difference, K.")
    p.add_argument("--output", type=Path,
                   default=Path("build/nerva_resolved_transient"))
    return p.parse_args()


def sha256(path: Path) -> str:
    digest=hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda:f.read(2**20),b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    a=parse_args()
    if a.steps<1 or not math.isfinite(a.dt_s) or a.dt_s<=0:
        raise ValueError("steps and dt must be positive")
    if not 0<=a.max_unresolved_fraction<=1:
        raise ValueError("unresolved fraction must lie in [0,1]")
    if a.allow_synthetic:
        if a.statepoint or a.transport_provenance:
            raise ValueError("synthetic source cannot claim real statepoint")
        source_kind="synthetic_reconstruction_unverified"
    else:
        if a.statepoint is None or a.transport_provenance is None:
            raise ValueError("real source requires statepoint and matching "
                             "transport provenance; otherwise use --allow-synthetic")
        prov=json.loads(a.transport_provenance.read_text(encoding="utf-8"))
        sp=prov.get("statepoint")
        if not isinstance(sp,dict) or not isinstance(sp.get("sha256"),str):
            raise RuntimeError("transport provenance lacks OpenMC statepoint hash")
        if not a.statepoint.is_file() or a.statepoint.suffix!=".h5":
            raise ValueError("invalid real OpenMC statepoint file")
        if sha256(a.statepoint)!=sp["sha256"]:
            raise RuntimeError("statepoint SHA-256 mismatches transport provenance")
        source_kind="existing_openmc_reconstruction_frozen_neutronics"

    heat=read_resolved_heating(
        a.fuel_reconstruction,a.tie_reconstruction,a.mesh_fields
    )
    if a.expected_power_mw is not None and (
        not math.isfinite(a.expected_power_mw)
        or not math.isclose(
            heat.total_openmc_power_w,a.expected_power_mw*1e6,
            rel_tol=1e-7
        )
    ):
        raise ValueError("mesh power differs from expected MW")
    frac=heat.unresolved_power_w/heat.total_openmc_power_w
    if frac>a.max_unresolved_fraction:
        raise ValueError("unresolved nuclear heat exceeds configured ceiling")
    p=ResolvedParameters(
        a.fuel_solid_capacity_j_k, a.fuel_gas_capacity_j_k,
        a.fuel_ua_w_k, a.tie_solid_capacity_j_k,
        a.tie_supply_capacity_j_k,a.tie_return_capacity_j_k,
        a.tie_supply_ua_w_k,a.tie_return_ua_w_k,
        hydrogen_cp_reference_j_kg_k=a.h2_cp_reference_j_kg_k,
        enthalpy_model=a.gas_enthalpy_model,
    )
    p.validate()
    state=initial_resolved_state(
        heat,solid_temperature_k=a.initial_solid_k,
        gas_temperature_k=a.initial_gas_k
    )
    old_state=state
    rows=[]
    for k in range(a.steps):
        step=advance_resolved(heat,state,p,a.inlet_temperature_k,a.dt_s)
        state=step.state
        row={
            "time_s":(k+1)*a.dt_s,
            "mean_fuel_outlet_k":float(np.mean(step.fuel_outlet_t_k)),
            "max_fuel_outlet_k":float(np.max(step.fuel_outlet_t_k)),
            "mean_tie_return_outlet_k":float(np.mean(step.tie_outlet_t_k)),
            "max_tie_return_outlet_k":float(np.max(step.tie_outlet_t_k)),
            "max_fuel_solid_k":float(np.max(state.fuel_solid_t_k)),
            "max_tie_solid_k":float(np.max(state.tie_solid_t_k)),
            "stored_energy_delta_j":step.energy_stored_delta_j,
            "energy_residual_j":step.energy_residual_j,
            "unresolved_stored_energy_j":state.unresolved_energy_j,
            "tie_coupling_max_iterations":step.tie_coupling_max_iterations,
        }
        rows.append(row)
        print(
            f"step={k+1}/{a.steps}, hottest fuel outlet "
            f"{row['max_fuel_outlet_k']:.3f} K, return outlet "
            f"{row['max_tie_return_outlet_k']:.3f} K, "
            f"energy residual {row['energy_residual_j']:.3g} J"
        )
    root=a.output
    root.mkdir(parents=True,exist_ok=True)
    details={
        "status":"PASS",
        "source_kind":source_kind,
        "thermal_scope":"per-channel fuel and shared-solid individual "
                        "counterflow ties; fixed flow and thermo pressure",
        "neutron_feedback":"none, existing nuclear deposition shape fixed",
        "historical_nerva_validation":False,
        "power_w":heat.total_openmc_power_w,
        "unresolved_power_w":heat.unresolved_power_w,
        "unresolved_fraction":frac,
        "fuel_channel_count":int(heat.fuel_flow_kg_s.size),
        "tie_tube_count":int(heat.tie_flow_kg_s.size),
        "total_fuel_flow_kg_s":heat.total_fuel_flow_kg_s,
        "total_tie_flow_kg_s":heat.total_tie_flow_kg_s,
        "step_s":a.dt_s,"steps":a.steps,
        "enthalpy_model":a.gas_enthalpy_model,
        "input_parameters_assumed_not_calibrated":True,
        "inputs_sha256":{
            "mesh_fields":sha256(a.mesh_fields),
            "fuel_reconstruction":sha256(a.fuel_reconstruction),
            "tie_reconstruction":sha256(a.tie_reconstruction),
            **({"statepoint":sha256(a.statepoint)} if a.statepoint else {}),
        },
        "history":rows,
    }
    if a.refine_levels != 0:
        convergence = refine_resolved_timestep(
            heat, old_state, p, a.inlet_temperature_k,
            a.steps*a.dt_s, base_steps=a.steps,
            levels=a.refine_levels,
            tolerance_k=a.refine_tolerance_k,
        )
        details["temporal_refinement"] = asdict(convergence)
        (root/"temporal_convergence_report.json").write_text(
            json.dumps(details["temporal_refinement"],indent=2)+"\n",
            encoding="utf-8",
        )
        print("Time-refinement audit: "+convergence.status+
              f", finest-state difference={convergence.finest_difference_k:.6g} K")
    (root/"resolved_transient_summary.json").write_text(
        json.dumps(details,indent=2)+"\n",encoding="utf-8"
    )
    with (root/"resolved_transient_history.csv").open("w",newline="",
         encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    np.savez_compressed(
        root/"resolved_transient_final_state.npz",
        fuel_solid_t_k=state.fuel_solid_t_k,
        fuel_h2_t_k=state.fuel_h2_t_k,
        tie_solid_t_k=state.tie_solid_t_k,
        tie_supply_t_k=state.tie_supply_t_k,
        tie_return_t_k=state.tie_return_t_k,
        fuel_outlet_t_k=state.fuel_h2_t_k[:,:,-1],
        tie_outlet_t_k=state.tie_return_t_k[:,0],
        unresolved_energy_j=np.array([state.unresolved_energy_j]),
    )
    if a.refine_levels != 0 and convergence.status != "PASS":
        print("Resolved NERVA temporal convergence: FAIL")
        return 2
    print("Resolved NERVA transient: PASS")
    return 0


if __name__=="__main__":
    raise SystemExit(main())
